/** Shuffle eighths: a long note and a short one, on the triplet grid. */
function sh(notes: string): string {
  return notes
    .trim()
    .split(/\s+/)
    .map((note, index) => `${index % 2 === 0 ? "/4t" : "/8t"} ${note}`)
    .join(" ");
}

