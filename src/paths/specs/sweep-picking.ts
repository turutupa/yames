function sweepExercise(args: Omit<ExerciseSpec, "pick" | "grade"> & { grade?: ExerciseSpec["grade"] }): ExerciseSpec {
  return {
    pick: "sweep",
    grade: "sweep",
    selfCheck: [ROLL_CHECK],
    ...args,
  };
}

